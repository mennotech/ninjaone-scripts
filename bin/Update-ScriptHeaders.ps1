<#
.SYNOPSIS
    Updates headers for existing NinjaOne scripts based on metadata.
.DESCRIPTION
    Automatically discovers all script files in the Windows, Linux, and macOS folders
    and updates their metadata headers when the corresponding NinjaOne metadata has changed.
    Creates stub files for metadata entries that do not have a corresponding local script.
    Only processes files with actual content (skips stub files with TODO placeholder).

    Requires scripts-metadata.json to be present (generated by Get-Scripts.ps1).

    Workflow:
    1. Run Get-Scripts.ps1 to refresh scripts-metadata.json
    2. Paste script content from NinjaOne GUI into any stub files
    3. Run this script to apply updated metadata headers to all content files
    4. Review changes and commit to Git

.OUTPUTS
    System.String
    Outputs status messages describing renamed, updated, and skipped files.

.NOTES
    Version: 1.1.0
    Author: NinjaOne Scripts Project
    Created: 2026-02-20

    Version History:
    1.1.0 - 2026-09-15 - Added repository-root path resolution and automatic stub creation
    1.0.0 - 2026-02-20 - Initial release

.LINK
    https://github.com/mennotech/ninja-one-scripts

.LICENSE
    MIT License - See LICENSE file in repository root
#>
[CmdletBinding()]
param()

begin {
    $repositoryRoot = Split-Path -Path $PSScriptRoot -Parent

    # Locate and load the metadata JSON produced by Get-Scripts.ps1
    $metadataDir = Join-Path -Path $repositoryRoot -ChildPath "db"
    $metadataPath = Join-Path -Path $metadataDir -ChildPath "scripts-metadata.json"

    if (-not (Test-Path -Path $metadataPath)) {
        Write-Error "Metadata file not found: $metadataPath. Run Get-Scripts.ps1 first to generate it."
        exit 1
    }

    try {
        $metadata = Get-Content $metadataPath -Raw -ErrorAction Stop | ConvertFrom-Json
    }
    catch {
        Write-Error "Failed to read metadata file '$metadataPath': $_"
        exit 1
    }

    # Function to extract existing metadata from header
    function Get-ExistingMetadata {
        param([string]$Content)

        $existing = @{}
        if ($Content -match 'NinjaOne Script ID:\s*(\d+)') { $existing.Id = [int]$matches[1] }
        if ($Content -match 'Last Updated:\s*([^\r\n]+)') { $existing.LastUpdated = $matches[1].Trim() }
        if ($Content -match 'Created On:\s*([^\r\n]+)') { $existing.CreatedOn = $matches[1].Trim() }
        if ($Content -match "(?ms)^(?:#|REM|//|') Description:\r?\n(?<Description>.*?)\r?\n(?:#|REM|//|')\s*\r?\n(?:#|REM|//|') Metadata:") {
            $existing.Description = (($matches.Description -split '\r?\n' | ForEach-Object {
                ($_ -replace "^(?:#|REM|//|')\s*", '').Trim()
            } | Where-Object { $_ }) -join "`n")
        }

        return $existing
    }

    function ConvertTo-NormalizedDescription {
        param([AllowNull()][string]$Description)

        $normalizedDescription = (($Description -replace '\\n', "`n") -split '[\r\n]+' |
            ForEach-Object { $_.Trim() } |
            Where-Object { $_ }) -join "`n"
        if ($normalizedDescription) {
            return $normalizedDescription
        }

        return "No description provided"
    }

    function New-ScriptStub {
        param(
            [Parameter(Mandatory = $true)]
            [PSCustomObject]$ScriptMetadata
        )

        $osType = $ScriptMetadata.operatingSystems[0]
        $osFolder = switch ($osType.ToLower()) {
            'windows' { 'Windows' }
            'mac' { 'macOS' }
            'macos' { 'macOS' }
            'linux' { 'Linux' }
            default { 'Unknown' }
        }
        $languageFolder = if ($ScriptMetadata.language) {
            $ScriptMetadata.language.Substring(0, 1).ToUpper() + $ScriptMetadata.language.Substring(1).ToLower()
        }
        else {
            'Unknown'
        }
        $extension = switch ($ScriptMetadata.language.ToLower()) {
            'powershell' { '.ps1' }
            { $_ -in 'batch', 'batchfile' } { '.bat' }
            { $_ -in 'bash', 'sh' } { '.sh' }
            'python' { '.py' }
            'javascript' { '.js' }
            'vbscript' { '.vbs' }
            default { '.txt' }
        }
        $commentChar = switch ($ScriptMetadata.language.ToLower()) {
            'powershell' { '#' }
            { $_ -in 'batch', 'batchfile' } { 'REM' }
            { $_ -in 'bash', 'sh' } { '#' }
            'python' { '#' }
            'javascript' { '//' }
            'vbscript' { "'" }
            default { '#' }
        }

        $scriptName = $ScriptMetadata.name -replace '[<>:"/\\|?*]', '_'
        $folderPath = Join-Path -Path $repositoryRoot -ChildPath "$osFolder\$languageFolder"
        $filePath = Join-Path -Path $folderPath -ChildPath "$($ScriptMetadata.id)-$scriptName$extension"
        $updateDate = [DateTimeOffset]::FromUnixTimeSeconds($ScriptMetadata.updatedOn).DateTime.ToString('yyyy-MM-dd HH:mm:ss')
        $createDate = [DateTimeOffset]::FromUnixTimeSeconds($ScriptMetadata.createdOn).DateTime.ToString('yyyy-MM-dd')
        $formattedDescription = if ($ScriptMetadata.description) {
            $description = $ScriptMetadata.description -replace '\\n', "`n"
            ($description -split '[\r\n]+' | Where-Object { $_.Trim() } | ForEach-Object { $_.Trim() }) -join "`n$commentChar   "
        }
        else {
            'No description provided'
        }

        $header = @"
$commentChar --- NINJAONE MANAGED HEADER START ---
$commentChar ==============================================================================
$commentChar Script Name: $($ScriptMetadata.name)
$commentChar ==============================================================================
$commentChar
$commentChar Description:
$commentChar   $formattedDescription
$commentChar
$commentChar Metadata:
$commentChar   - NinjaOne Script ID: $($ScriptMetadata.id)
$commentChar   - Language: $($ScriptMetadata.language)
$commentChar   - OS Type: $osType
$commentChar   - Architecture: $($ScriptMetadata.architecture -join ', ')
$commentChar   - Created By: $(if ($ScriptMetadata.createdBy) { $ScriptMetadata.createdBy } else { 'N/A' })
$commentChar   - Created On: $createDate
$commentChar   - Last Updated By: $(if ($ScriptMetadata.lastUpdatedBy) { $ScriptMetadata.lastUpdatedBy } else { 'N/A' })
$commentChar   - Last Updated: $updateDate
$commentChar   - Active: $($ScriptMetadata.active)
$commentChar
"@
    $header += "`n"

        if ($ScriptMetadata.scriptParameters -and $ScriptMetadata.scriptParameters.Count -gt 0) {
            $header += "$commentChar Script Parameters:`n"
            foreach ($scriptParameter in $ScriptMetadata.scriptParameters) {
                $parameterDescription = if ($scriptParameter.description) {
                    $description = $scriptParameter.description -replace '\\n', "`n"
                    ($description -split '[\r\n]+' | Where-Object { $_.Trim() } | ForEach-Object { $_.Trim() }) -join ' '
                }
                else {
                    ''
                }
                $header += "$commentChar   - $($scriptParameter.name): $parameterDescription`n"
            }
            $header += "$commentChar`n"
        }

        if ($ScriptMetadata.scriptVariables -and $ScriptMetadata.scriptVariables.Count -gt 0) {
            $header += "$commentChar Script Variables (NinjaOne):`n"
            foreach ($scriptVariable in $ScriptMetadata.scriptVariables) {
                $required = if ($scriptVariable.required) { 'Required' } else { 'Optional' }
                $variableDescription = if ($scriptVariable.description) {
                    $description = $scriptVariable.description -replace '\\n', "`n"
                    ($description -split '[\r\n]+' | Where-Object { $_.Trim() } | ForEach-Object { $_.Trim() }) -join ' '
                }
                else {
                    ''
                }
                $header += "$commentChar   - $($scriptVariable.id) ($($scriptVariable.type), $required): $variableDescription`n"
                if ($scriptVariable.defaultValue) {
                    $header += "$commentChar     Default: $($scriptVariable.defaultValue)`n"
                }
            }
            $header += "$commentChar`n"
        }

        $header += @"
$commentChar ==============================================================================
$commentChar --- NINJAONE MANAGED HEADER END ---
    $commentChar
$commentChar TODO: Paste script content from NinjaOne GUI here
"@

        if (-not (Test-Path -Path $folderPath)) {
            New-Item -Path $folderPath -ItemType Directory -Force -ErrorAction Stop | Out-Null
        }
        Set-Content -Path $filePath -Value $header -Encoding UTF8 -ErrorAction Stop

        return $filePath
    }
}

end {
    # Discover all script files
    Write-Host "Scanning for script files..." -ForegroundColor Cyan
    $scriptDirectories = "Windows", "Linux", "macOS" | ForEach-Object {
        Join-Path -Path $repositoryRoot -ChildPath $_
    }
    $allFiles = Get-ChildItem -Path $scriptDirectories -Recurse -File -ErrorAction SilentlyContinue |
        Where-Object { $_.Extension -in '.ps1', '.bat', '.sh', '.py', '.js', '.vbs', '.txt' }

    Write-Host "Found $($allFiles.Count) script file(s)" -ForegroundColor Gray
    Write-Host ""

    $skippedCount = 0
    $updatedCount = 0
    $renamedCount = 0
    $createdCount = 0

    foreach ($file in $allFiles) {
        $fileName = $file.BaseName

        # Extract Script ID from filename (format: ID-ScriptName)
        $scriptId = $null
        if ($fileName -match '^(\d+)-') {
            $scriptId = [int]$matches[1]
        }

        # Find matching metadata by ID (preferred) or name (fallback for old files)
        if ($scriptId) {
            $scriptMeta = $metadata | Where-Object { $_.id -eq $scriptId }
        }
        else {
            $scriptMeta = $metadata | Where-Object { $_.name -eq $fileName }
        }

        if (-not $scriptMeta) {
            Write-Verbose "No metadata found for: $fileName"
            $skippedCount++
            continue
        }

        # Build expected filename with Script ID prefix
        $scriptName = $scriptMeta.name -replace '[<>:"/\\|?*]', '_'
        $expectedBaseName = "$($scriptMeta.id)-$scriptName"
        $expectedFileName = "$expectedBaseName$($file.Extension)"

        # Check if file needs to be renamed
        if ($file.Name -ne $expectedFileName) {
            $newPath = Join-Path -Path $file.DirectoryName -ChildPath $expectedFileName

            # Check if target already exists
            if (Test-Path $newPath) {
                Write-Warning "Cannot rename '$($file.Name)' to '$expectedFileName' - target already exists"
                $skippedCount++
                continue
            }

            try {
                Rename-Item -Path $file.FullName -NewName $expectedFileName -ErrorAction Stop
                $relativePath = $file.FullName -replace [regex]::Escape($PWD.Path + '\'), ''
                Write-Host "  [RENAME] $relativePath → $expectedFileName" -ForegroundColor Cyan
                $renamedCount++
                # Update file reference for subsequent processing
                $file = Get-Item $newPath
            }
            catch {
                Write-Warning "Failed to rename $($file.Name): $_"
                $skippedCount++
                continue
            }
        }

        # Read current content
        $content = Get-Content $file.FullName -Raw -ErrorAction SilentlyContinue

        if (-not $content) {
            Write-Verbose "Empty file: $($file.FullName)"
            $skippedCount++
            continue
        }

        # Check if it's a stub file (contains TODO)
        if ($content -match 'TODO: Paste script content from NinjaOne GUI') {
            Write-Verbose "Stub file: $($file.FullName)"
            $skippedCount++
            continue
        }

        # Check existing metadata
        $existing = Get-ExistingMetadata -Content $content
        $updateDate = [DateTimeOffset]::FromUnixTimeSeconds($scriptMeta.updatedOn).DateTime.ToString("yyyy-MM-dd HH:mm:ss")
        $createDate = [DateTimeOffset]::FromUnixTimeSeconds($scriptMeta.createdOn).DateTime.ToString("yyyy-MM-dd")
        $metadataDescription = ConvertTo-NormalizedDescription -Description $scriptMeta.description
        $hasManagedHeaderMarkers = $content -match "(?m)^(?:#|REM|//|') --- NINJAONE MANAGED HEADER START ---\r?$" -and
            $content -match "(?m)^(?:#|REM|//|') --- NINJAONE MANAGED HEADER END ---\r?$"

        if (-not $hasManagedHeaderMarkers) {
            Write-Warning "Managed metadata header markers were not found in '$($file.FullName)'. Skipping to preserve script content."
            $skippedCount++
            continue
        }

        # Determine if update is needed
        $needsUpdate = $false
        $reason = ""

        if (-not $existing.Id) {
            $needsUpdate = $true
            $reason = "No header found"
        }
        elseif ($existing.Id -ne $scriptMeta.id) {
            $needsUpdate = $true
            $reason = "Script ID mismatch"
        }
        elseif ($existing.LastUpdated -ne $updateDate) {
            $needsUpdate = $true
            $reason = "Metadata updated in NinjaOne"
        }
        elseif ($existing.Description -ne $metadataDescription) {
            $needsUpdate = $true
            $reason = "Description updated in NinjaOne"
        }

        if (-not $needsUpdate) {
            Write-Host "  [SKIP] Up-to-date: $($file.FullName -replace [regex]::Escape($PWD.Path + '\'), '')" -ForegroundColor Gray
            $skippedCount++
            continue
        }

        # Build metadata header
        $osType = $scriptMeta.operatingSystems[0]

        # Determine comment character based on language
        $commentChar = switch ($scriptMeta.language.ToLower()) {
            'powershell' { '#' }
            { $_ -in 'batch', 'batchfile' } { 'REM' }
            { $_ -in 'bash', 'sh' } { '#' }
            'python' { '#' }
            'javascript' { '//' }
            'vbscript' { "'" }
            default { '#' }
        }

        # Format description with proper comment markers for multi-line content
        $formattedDescription = if ($scriptMeta.description) {
            # Handle both literal \n and actual newlines
            $desc = $scriptMeta.description -replace '\\n', "`n"
            # Split by newlines, trim each line, filter empty lines, and join with proper comment prefix
            ($desc -split '[\r\n]+' | Where-Object { $_.Trim() } | ForEach-Object { $_.Trim() }) -join "`n$commentChar   "
        } else {
            "No description provided"
        }

        $header = @"
$commentChar --- NINJAONE MANAGED HEADER START ---
$commentChar ==============================================================================
$commentChar Script Name: $($scriptMeta.name)
$commentChar ==============================================================================
$commentChar
$commentChar Description:
$commentChar   $formattedDescription
$commentChar
$commentChar Metadata:
$commentChar   - NinjaOne Script ID: $($scriptMeta.id)
$commentChar   - Language: $($scriptMeta.language)
$commentChar   - OS Type: $osType
$commentChar   - Architecture: $($scriptMeta.architecture -join ', ')
$commentChar   - Created By: $(if ($scriptMeta.createdBy) { $scriptMeta.createdBy } else { 'N/A' })
$commentChar   - Created On: $createDate
$commentChar   - Last Updated By: $(if ($scriptMeta.lastUpdatedBy) { $scriptMeta.lastUpdatedBy } else { 'N/A' })
$commentChar   - Last Updated: $updateDate
$commentChar   - Active: $($scriptMeta.active)

"@

        # Add script variables if present
        if ($scriptMeta.scriptVariables -and $scriptMeta.scriptVariables.Count -gt 0) {
            $header += "$commentChar Script Variables (NinjaOne):`n"
            foreach ($var in $scriptMeta.scriptVariables) {
                $required = if ($var.required) { "Required" } else { "Optional" }
                # Format description with proper comment markers for multi-line content
                $varDesc = if ($var.description) {
                    $desc = $var.description -replace '\\n', "`n"
                    ($desc -split '[\r\n]+' | Where-Object { $_.Trim() } | ForEach-Object { $_.Trim() }) -join " "
                } else { "" }
                $header += "$commentChar   - $($var.id) ($($var.type), $required): $varDesc`n"
                if ($var.defaultValue) {
                    $header += "$commentChar     Default: $($var.defaultValue)`n"
                }
            }
            $header += "$commentChar`n"
        }

        $header += @"
$commentChar ==============================================================================
$commentChar --- NINJAONE MANAGED HEADER END ---

"@

        # Replace only the explicitly managed header.
        $lines = $content -split "`r?`n"
        $headerStartIndex = $null
        $headerEndIndex = $null
        for ($index = 0; $index -lt $lines.Count; $index++) {
            if ($lines[$index].Trim() -match "^(?:#|REM|//|') --- NINJAONE MANAGED HEADER START ---$") {
                $headerStartIndex = $index
            }
            elseif ($null -ne $headerStartIndex -and $lines[$index].Trim() -match "^(?:#|REM|//|') --- NINJAONE MANAGED HEADER END ---$") {
                $headerEndIndex = $index
                break
            }
        }

        if ($null -eq $headerStartIndex -or $null -eq $headerEndIndex) {
            Write-Warning "Could not identify the managed metadata header in '$($file.FullName)'. Skipping to preserve script comments."
            $skippedCount++
            continue
        }

        $prefix = if ($headerStartIndex -gt 0) {
            ($lines[0..($headerStartIndex - 1)] -join "`n") + "`n"
        } else { "" }
        $codeStartIndex = $headerEndIndex + 1
        while ($codeStartIndex -lt $lines.Count -and -not $lines[$codeStartIndex].Trim()) {
            $codeStartIndex++
        }

        # Get the script-owned content, including comments and directives.
        $actualCode = if ($codeStartIndex -lt $lines.Count) {
            $lines[$codeStartIndex..($lines.Count - 1)] -join "`n"
        } else { "" }

        # Combine new header with actual code
        $newContent = $prefix + $header + $actualCode

        # Write back to file
        try {
            Set-Content -Path $file.FullName -Value $newContent -Encoding UTF8 -NoNewline -ErrorAction Stop
            $relativePath = $file.FullName -replace [regex]::Escape($PWD.Path + '\'), ''
            Write-Host "  [UPDATE] $relativePath ($reason)" -ForegroundColor Green
            $updatedCount++
        }
        catch {
            Write-Warning "Failed to update $($file.FullName): $_"
        }
    }

    $localScriptIds = @($allFiles | ForEach-Object {
        if ($_.BaseName -match '^(\d+)-') {
            [int]$matches[1]
        }
    })
    $missingScripts = @($metadata | Where-Object { [int]$_.id -notin $localScriptIds })

    foreach ($missingScript in $missingScripts) {
        try {
            $stubPath = New-ScriptStub -ScriptMetadata $missingScript
            $relativePath = $stubPath -replace [regex]::Escape($repositoryRoot + '\'), ''
            Write-Host "  [CREATE] $relativePath" -ForegroundColor Green
            $createdCount++
        }
        catch {
            Write-Warning "Failed to create stub for '$($missingScript.name)': $_"
        }
    }

    # Summary
    Write-Host ""
    Write-Host "Summary:" -ForegroundColor Cyan
    Write-Host "  Total files found: $($allFiles.Count)" -ForegroundColor Gray
    Write-Host "  Renamed: $renamedCount" -ForegroundColor Cyan
    Write-Host "  Updated: $updatedCount" -ForegroundColor Green
    Write-Host "  Created: $createdCount" -ForegroundColor Green
    Write-Host "  Skipped: $skippedCount" -ForegroundColor Yellow
    Write-Host ""
    Write-Host "Header update complete!" -ForegroundColor Cyan
}
